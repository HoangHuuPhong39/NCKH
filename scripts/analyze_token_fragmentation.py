#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
scripts/analyze_token_fragmentation.py
Phân tích hiện tượng phân mảnh BPE Token (Subword Fertility, Token Fragmentation Ratio)
giữa Baseline tiếng Anh và 5 biến thể hình thái / chính tả tiếng Việt.
Sử dụng chính xác AutoTokenizer của Meta-Llama-3-8B-Instruct (128k vocabulary).
Tất cả số liệu tính toán từ file benchmark thực tế, không bịa số.
"""

import json
from pathlib import Path
import sys
import numpy as np
from transformers import AutoTokenizer

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

PROJECT_ROOT = Path(__file__).resolve().parent.parent

def analyze_benchmarks():
    # 1. Nạp tokenizer chuẩn của Meta Llama 3 (128k vocabulary)
    # Thử nạp từ unsloth mirror (cùng trọng số và tokenizer.json với Meta-Llama-3-8B-Instruct)
    tokenizer_name = "unsloth/llama-3-8b-Instruct"
    print(f"[*] Đang nạp AutoTokenizer: {tokenizer_name}...")
    tok = AutoTokenizer.from_pretrained(tokenizer_name)
    vocab_size = len(tok)
    print(f"[+] Nạp thành công! Kích thước từ vựng (Vocabulary size): {vocab_size} tokens.")

    vn_path = PROJECT_ROOT / "AI_Security_Scanner" / "data" / "vietnamese_benchmark.json"
    en_path = PROJECT_ROOT / "AI_Security_Scanner" / "data" / "english_baseline_benchmark.json"

    with open(vn_path, "r", encoding="utf-8") as f:
        vn_cases = json.load(f)["test_cases"]

    with open(en_path, "r", encoding="utf-8") as f:
        en_cases = json.load(f)["test_cases"]

    # Phân nhóm theo các tập dữ liệu thực tế (mỗi biến thể có 30 câu)
    cohorts = {
        "English Baseline": [c["prompt"] for c in en_cases],
        "Standard VI (NFC)": [c["prompt"] for c in vn_cases if c.get("linguistic_variant") == "standard_vi"],
        "No Diacritics": [c["prompt"] for c in vn_cases if c.get("linguistic_variant") == "no_diacritics"],
        "Teencode / Slang": [c["prompt"] for c in vn_cases if c.get("linguistic_variant") == "teencode_slang"],
        "Code-Switching": [c["prompt"] for c in vn_cases if c.get("linguistic_variant") == "code_switching"],
        "Unicode NFD": [c["prompt"] for c in vn_cases if c.get("linguistic_variant") == "unicode_nfd"],
    }

    results = {}
    print(f"\n{'Variant / Language':<22} | {'Words':<6} | {'Tokens':<6} | {'Bytes':<6} | {'Fertility (T/W)':<15} | {'Frag vs EN':<11} | {'Frag vs StdVI':<13}")
    print("-" * 95)

    en_fertility = None
    std_fertility = None

    for name, prompts in cohorts.items():
        words_list = []
        tokens_list = []
        bytes_list = []
        fertilities = []

        for p in prompts:
            # Đếm số từ theo khoảng trắng (word count chuẩn)
            words = len(p.split())
            # Mã hóa qua BPE tokenizer của Llama 3
            tokens = len(tok.encode(p))
            # Chiều dài byte UTF-8
            n_bytes = len(p.encode("utf-8"))

            words_list.append(words)
            tokens_list.append(tokens)
            bytes_list.append(n_bytes)
            fertilities.append(tokens / words if words > 0 else 1.0)

        mean_words = float(np.mean(words_list))
        mean_tokens = float(np.mean(tokens_list))
        mean_bytes = float(np.mean(bytes_list))
        mean_fert = float(np.mean(fertilities))

        if name == "English Baseline":
            en_fertility = mean_fert
        if name == "Standard VI (NFC)":
            std_fertility = mean_fert

        results[name] = {
            "mean_words": mean_words,
            "mean_tokens": mean_tokens,
            "mean_bytes": mean_bytes,
            "fertility": mean_fert,
        }

    # Tính tỷ lệ tương đối so với English và Standard Vietnamese
    for name, r in results.items():
        frag_en = r["fertility"] / en_fertility if en_fertility else 1.0
        frag_std = r["fertility"] / std_fertility if std_fertility else 1.0
        r["frag_vs_en"] = frag_en
        r["frag_vs_std"] = frag_std

        print(f"{name:<22} | {r['mean_words']:<6.1f} | {r['mean_tokens']:<6.1f} | {r['mean_bytes']:<6.1f} | "
              f"{r['fertility']:<15.3f} | {frag_en:<11.2f}x | {frag_std:<13.2f}x")

    # 2. Xuất bảng LaTeX Table 2
    out_tex = PROJECT_ROOT / "paper" / "tables" / "token_fragmentation_table.tex"
    out_tex.parent.mkdir(parents=True, exist_ok=True)
    with open(out_tex, "w", encoding="utf-8") as f:
        f.write("% Auto-generated by scripts/analyze_token_fragmentation.py (Meta-Llama-3-8B-Instruct AutoTokenizer)\n")
        f.write("\\begin{table}[t]\n")
        f.write("\\centering\n")
        f.write("\\small\n")
        f.write("\\caption{Quantitative BPE Token Fragmentation Analysis Across Linguistic Variants on Meta-Llama-3-8B-Instruct ($N_{\\text{cases}}=30$ per variant).}\n")
        f.write("\\label{tab:token_fragmentation}\n")
        f.write("\\resizebox{\\textwidth}{!}{%\n")
        f.write("\\begin{tabular}{lcccccc}\n")
        f.write("\\toprule\n")
        f.write("\\textbf{Linguistic Variant} & \\textbf{Words} & \\textbf{Tokens} & \\textbf{Bytes} & \\textbf{Fertility ($F$)} & \\textbf{vs. EN} & \\textbf{vs. Std VI} \\\\\n")
        f.write("\\midrule\n")
        for name, r in results.items():
            f.write(f"{name} & {r['mean_words']:.1f} & {r['mean_tokens']:.1f} & {r['mean_bytes']:.1f} & {r['fertility']:.3f} & {r['frag_vs_en']:.2f}$\\times$ & {r['frag_vs_std']:.2f}$\\times$ \\\\\n")
        f.write("\\bottomrule\n")
        f.write("\\end{tabular}%\n")
        f.write("}\n")
        f.write("\\end{table}\n")

    # 3. Xuất JSON phục vụ vẽ đồ thị và phân tích
    out_json = PROJECT_ROOT / "AI_Security_Scanner" / "experiments" / "results" / "token_fragmentation_metrics.json"
    out_json.parent.mkdir(parents=True, exist_ok=True)
    with open(out_json, "w", encoding="utf-8") as f:
        json.dump(results, f, indent=2)

    print(f"\n[+] Đã ghi bảng LaTeX: {out_tex}")
    print(f"[+] Đã ghi JSON metrics: {out_json}")

if __name__ == "__main__":
    analyze_benchmarks()
